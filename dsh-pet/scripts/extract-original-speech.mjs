/** 从固定 Git 基线提取内置台词配对；只向 stdout 输出，不修改显示文案或工作区。 */
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const ORIGINAL = 'fb38ce6';
const DISPLAY = '292f841';
const pairs = new Map();

function source(ref, path) {
  return execFileSync('git', ['show', `${ref}:dsh-pet/${path}`], { cwd: ROOT, encoding: 'utf8' });
}

function add(display, original) {
  if (display === original || !/\p{Script=Han}/u.test(original)) return;
  const previous = pairs.get(display);
  if (previous !== undefined && previous !== original) throw new Error(`Ambiguous speech: ${display}`);
  pairs.set(display, original);
}

function literals(text, path, declarations) {
  const tree = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true);
  const found = [];
  function visit(node) {
    if (ts.isStringLiteral(node) && !(ts.isPropertyAssignment(node.parent) && node.parent.name === node)) {
      found.push(node.text);
    }
    ts.forEachChild(node, visit);
  }
  for (const statement of tree.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      if (declarations.includes(declaration.name.getText(tree))) visit(declaration.initializer);
    }
  }
  return found;
}

function table(path, declarations) {
  const originals = literals(source(ORIGINAL, path), path, declarations);
  const displays = literals(source(DISPLAY, path), path, declarations);
  if (originals.length !== displays.length) throw new Error(`Table shape changed: ${path}`);
  displays.forEach((display, index) => add(display, originals[index]));
}

const configPath = 'assets/config.jsonc';
const originalConfig = ts.parseConfigFileTextToJson(configPath, source(ORIGINAL, configPath)).config;
const displayConfig = ts.parseConfigFileTextToJson(configPath, source(DISPLAY, configPath)).config;
for (const key of ['sleepRefuseTexts', 'sleepStartTexts', 'sleepEndTexts', 'workStatusTexts']) {
  const originals = originalConfig[key].flat();
  const displays = displayConfig[key].flat();
  if (originals.length !== displays.length) throw new Error(`Config shape changed: ${key}`);
  displays.forEach((display, index) => add(display, originals[index]));
}
